// Completes the Next.js standalone build (.next/standalone) so it can be
// deployed and run on its own:
// - copies .next/static and public/, which `next build` leaves out
// - adds a root server.js that starts the nested apps/web/server.js, so the
//   entry point is simply `server.js` inside the standalone folder
// Run after `next build` (see the build:webpack script).
import { cpSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const standalone = path.join(webDir, '.next', 'standalone');
// outputFileTracingRoot is the repo root, so the app sits at apps/web inside standalone.
const appInStandalone = path.join(standalone, 'apps', 'web');

if (!existsSync(path.join(appInStandalone, 'server.js'))) {
  console.error(`Standalone server not found at ${appInStandalone}/server.js (is output: 'standalone' set?)`);
  process.exit(1);
}

cpSync(path.join(webDir, '.next', 'static'), path.join(appInStandalone, '.next', 'static'), { recursive: true });
if (existsSync(path.join(webDir, 'public'))) {
  cpSync(path.join(webDir, 'public'), path.join(appInStandalone, 'public'), { recursive: true });
}

writeFileSync(
  path.join(standalone, 'server.js'),
  `// Entry point for hosts: starts the Next.js standalone server (generated by prepare-standalone.mjs).
// Listen on all interfaces unless HOSTNAME is set explicitly for this app.
process.env.HOSTNAME = process.env.RINSEOPS_HOSTNAME || '0.0.0.0';
require('./apps/web/server.js');
`,
);

console.log(`Standalone build ready: ${path.relative(webDir, standalone)}/server.js`);
